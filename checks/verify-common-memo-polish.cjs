const {chromium}=require('C:/Users/任伟的机械革命/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');

(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  try{
    const page=await browser.newPage({viewport:{width:1375,height:992}}),errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.route('**/api/shiyu/auth/**',route=>route.fulfill({status:route.request().url().includes('/wechat/')?200:503,json:{}}));
    await page.addInitScript(()=>{
      window.__cardAudioStarts=0;
      const start=AudioBufferSourceNode.prototype.start;
      AudioBufferSourceNode.prototype.start=function(...args){window.__cardAudioStarts++;return start.apply(this,args)};
    });
    await page.goto('http://127.0.0.1:4337/',{waitUntil:'domcontentloaded'});
    await page.waitForFunction(()=>window.ShiyuCornerModules);
    await page.evaluate(()=>{signed=true;prefs.accountProfile={id:'common-memo-polish-qa'};prefs.mode='dark';prefs.theme='base';prefs.cornerCloseGuideAcknowledgedV1={'common-memo-polish-qa':true};localStorage.setItem('yiyu-prototype-v1',JSON.stringify({data,prefs,overrides,styles,signed}));render()});
    await page.goto('http://127.0.0.1:4337/?corner=common',{waitUntil:'domcontentloaded'});
    await page.waitForSelector('#my-corner[open][data-corner-module=common] .corner-card.is-center');
    const previous=page.locator('[data-corner-page="-1"]'),next=page.locator('[data-corner-page="1"]');
    while(!await previous.isDisabled())await previous.click();
    await page.waitForTimeout(500);
    const first=await page.locator('.corner-card.is-center').getAttribute('data-corner-card');
    await page.evaluate(()=>window.__cardAudioStarts=0);
    await page.mouse.move(680,170);await page.mouse.wheel(0,-120);
    await page.waitForTimeout(75);
    const stretch=Number.parseFloat(await page.locator('.corner-card.is-center').evaluate(el=>el.style.getPropertyValue('--fan-x')));
    assert(stretch>0,'first card stretches without wrapping');
    await page.waitForTimeout(700);
    assert.equal(await page.locator('.corner-card.is-center').getAttribute('data-corner-card'),first);
    assert(Math.abs(Number.parseFloat(await page.locator('.corner-card.is-center').evaluate(el=>el.style.getPropertyValue('--fan-x'))))<1,'first card rebounds');
    assert.equal(await page.evaluate(()=>window.__cardAudioStarts),0,'edge stretch is silent');
    while(!await next.isDisabled())await next.click();
    await page.waitForTimeout(500);
    const last=await page.locator('.corner-card.is-center').getAttribute('data-corner-card');
    await page.mouse.wheel(0,120);await page.waitForTimeout(75);
    assert(Number.parseFloat(await page.locator('.corner-card.is-center').evaluate(el=>el.style.getPropertyValue('--fan-x')))<0,'last card stretches without wrapping');
    await page.waitForTimeout(700);
    assert.equal(await page.locator('.corner-card.is-center').getAttribute('data-corner-card'),last);
    await page.goto('http://127.0.0.1:4337/?corner=memo',{waitUntil:'domcontentloaded'});
    await page.waitForSelector('#my-corner[open][data-corner-module=memo] .memo-cover.is-active');
    await page.waitForTimeout(850);
    assert.equal(await page.locator('.memo-paper-app').evaluate(el=>getComputedStyle(el).backgroundColor),'rgba(0, 0, 0, 0)');
    fs.mkdirSync('.local/common-memo-polish',{recursive:true});
    await page.screenshot({path:'.local/common-memo-polish/memo-dark.png'});
    const card=page.locator('.memo-cover.is-active');
    await card.hover();await page.waitForTimeout(230);
    const discard=card.locator('.memo-cover-discard');
    const faint=Number(await discard.evaluate(el=>getComputedStyle(el).opacity));
    await discard.hover();await page.waitForTimeout(230);
    assert(Number(await discard.evaluate(el=>getComputedStyle(el).opacity))>faint,'discard becomes clearer on hover');
    await card.hover();await page.waitForTimeout(230);
    const archive=card.locator('.memo-cover-archive');
    const archiveFaint=Number(await archive.evaluate(el=>getComputedStyle(el).opacity));
    await archive.hover();await page.waitForTimeout(230);
    assert(Number(await archive.evaluate(el=>getComputedStyle(el).opacity))>archiveFaint,'archive becomes clearer on hover');
    await page.evaluate(()=>window.__cardAudioStarts=0);
    const before=await page.locator('.memo-paper-app').getAttribute('data-active-card');
    await page.mouse.move(685,230);await page.mouse.wheel(0,120);
    await page.waitForFunction(before=>document.querySelector('.memo-paper-app')?.dataset.activeCard!==before,before);
    assert.equal(await page.evaluate(()=>window.__cardAudioStarts),1,'one sound for a memo wheel card change');
    await page.locator('[data-memo-view=archive]').click();
    assert.equal(await page.evaluate(()=>window.__cardAudioStarts),1,'switching memo views is silent');
    await page.locator('[data-memo-view=notes]').click();
    assert.equal(await page.evaluate(()=>window.__cardAudioStarts),1);
    await page.locator('#my-corner [data-module-title]').click();
    await page.waitForSelector('#my-corner[data-corner-module=todo]');
    assert.equal(await page.evaluate(()=>window.__cardAudioStarts),1,'switching modules is silent');
    assert.deepEqual(errors,[]);
    console.log('PASS common bounded wheel stretch/rebound; memo translucent background, hover actions, preview-only wheel sound');
  }finally{await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1});
