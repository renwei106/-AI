const {chromium}=require('C:/Users/任伟的机械革命/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs=require('node:fs'),assert=require('node:assert/strict');
let browser;
(async()=>{
  browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1288,height:1041}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/flow-theme.js',route=>route.fulfill({contentType:'text/javascript',body:fs.readFileSync('dist/flow-theme.js','utf8').replace('const FORM_START=10000,FORM_END=30000;','const FORM_START=1000,FORM_END=3000;')}));
  await page.goto('http://127.0.0.1:4318/?theme=flow',{waitUntil:'networkidle'});
  await page.evaluate(()=>{signed=true;prefs.flowStyle='form';persist();render();document.querySelector('.brand-guide')?.remove()});
  const canvas=page.locator('.flow-canvas'),cover=page.locator('.flow-cover');
  assert.equal(await canvas.getAttribute('data-target-particles'),await canvas.getAttribute('data-particles'),'all particles are assigned to the shape');
  await page.waitForTimeout(600);
  assert.equal(await cover.getAttribute('data-flow-state'),'chaos');
  assert.equal(Number(await canvas.getAttribute('data-formation')),0);
  await page.waitForTimeout(850);
  const middle=Number(await canvas.getAttribute('data-formation'));
  assert.equal(await cover.getAttribute('data-flow-state'),'forming');
  assert(middle>.05&&middle<.5,'formation advances continuously after the opening interval');
  await page.screenshot({path:'checks/flow-forming.png'});
  await page.waitForTimeout(1750);
  assert.equal(await cover.getAttribute('data-flow-state'),'formed');
  assert.equal(Number(await canvas.getAttribute('data-formation')),1);
  const placement=await page.evaluate(()=>{const copy=document.querySelector('.flow-copy').getBoundingClientRect(),particles=document.querySelector('.flow-cover').__inspirationSnapshot().particles;return{copyBottom:copy.bottom,minY:Math.min(...particles.map(p=>p.y))*innerHeight,maxY:Math.max(...particles.map(p=>p.y))*innerHeight,viewportHeight:innerHeight}});
  assert(placement.minY>=placement.copyBottom+20,'the completed form stays below the central copy');
  assert(placement.maxY>=placement.viewportHeight*.94,'the completed form reaches the bottom of the screen');
  await page.screenshot({path:'checks/flow-formed.png'});
  assert.deepEqual(errors,[]);
  console.log('PASS: all particles remain chaotic first, then converge continuously and finish together.');
})().catch(error=>{console.error(error);process.exitCode=1}).finally(async()=>browser?.close());
