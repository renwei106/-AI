const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('C:/Users/任伟的机械革命/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
let browser;
(async () => {
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, reducedMotion: 'reduce' });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:4327/'); await page.waitForFunction(() => window.__emergence);
  const behavior = await page.evaluate(async () => {
    const { defaultsFor, sanitize } = await import('./scenes.js'), e = window.__emergence.engine;
    const checks = [], check = (ok, message) => { if (!ok) throw Error(message); checks.push(message); };
    for (const id of ['birds', 'fish']) {
      e.setScene(id, { ...defaultsFor(id), count: 60, breeding: 'yes', birthInterval: 20, birthBatch: 3, populationCap: 80, replenish: 'no', predators: 0 });
      for (let i = 0; i < 1199; i++) e.step();
      check(e.particles.length === 60, id + ': no early birth'); e.step();
      check(e.particles.length === 63 && e.born === 3, id + ': actual fixed-step simulation births exactly 3 at 20 seconds');
      for (let i = 0; i < 20; i++) e.breedPopulation(20);
      check(e.particles.length === 80, id + ': hard population ceiling');
      e.setConfig({ ...e.config, breeding: 'no', count: 60 }); e.particles.length = 60;
      e.breedPopulation(60); check(e.particles.length === 60, id + ': disabled breeding stays disabled');
      e.setConfig({ ...e.config, breeding: 'yes' }); e.particles = []; e.breedPopulation(60);
      check(e.particles.length === 0, id + ': extinction does not spontaneously reproduce');
      e.setScene(id, { ...defaultsFor(id), count: 60, predators: 1, breeding: 'no', replenish: 'no', predatorBirthInterval: 300, birthMeals: 5, predatorCap: 3 });
      const hunter = e.predators[0];
      const feed = () => {
        const prey = e.model.create(e, 0); prey.x = hunter.x; prey.y = hunter.y;
        e.particles = [prey]; hunter.rest = 0; e.step();
      };
      feed(); check(hunter.meals === 1 && e.captured === 1 && hunter.rest === e.config.huntRest * 60, id + ': actual capture records food and rest duration');
      const nearby = e.model.create(e, 0); nearby.x = hunter.x; nearby.y = hunter.y; e.particles = [nearby]; e.step();
      check(e.captured === 1, id + ': resting predator cannot capture again');
      for (let i = 0; i < 4; i++) feed();
      e.particles = [e.model.create(e, 0)]; e.predatorBirthClock = 0;
      e.breedPopulation(299.9); check(e.predators.length === 1, id + ': well-fed predator still waits at least 300 seconds');
      e.breedPopulation(.1); check(e.predators.length === 2 && e.predatorBorn === 1 && hunter.meals === 0, id + ': at most one offspring and food requirement consumed');
      e.syncPredators(); e.setConfig({ ...e.config, speed: 1.2 }); e.step();
      check(e.predators.length === 2, id + ': offspring survives reconciliation and unrelated slider changes');
      e.breedPopulation(300); check(e.predators.length === 2, id + ': elapsed time alone cannot reproduce without food');
      hunter.meals = 5; e.breedPopulation(.01); check(e.predators.length === 3, id + ': feeding unlocks a due birth');
      hunter.meals = 100; e.breedPopulation(900); check(e.predators.length === 3, id + ': predator cap holds even with excess food and time');
      e.setConfig({ ...e.config, predators: 0 }); e.breedPopulation(900);
      check(e.predators.length === 0, id + ': zero predators disables offspring too');
      const safe = sanitize(id, { count: 200, populationCap: 60, predators: 4, predatorCap: 1 });
      check(safe.populationCap >= safe.count && safe.predatorCap >= safe.predators, id + ': limits cannot contradict initial quantities');
    }
    e.setScene('birds', defaultsFor('birds')); return checks;
  });
  await page.locator('#lifecycle summary').click();
  const slide = async (key, value) => page.locator('#control-' + key).evaluate((e, v) => { e.value = v; e.dispatchEvent(new Event('input', { bubbles: true })); }, value);
  await slide('predators', 1); await slide('birthInterval', 30); await slide('predatorBirthInterval', 600); await slide('huntRest', 8);
  await page.waitForTimeout(250); await page.reload(); await page.waitForFunction(() => window.__emergence);
  assert.equal(await page.locator('#control-birthInterval').inputValue(), '30');
  assert.equal(await page.locator('#control-predatorBirthInterval').inputValue(), '600');
  assert.equal(await page.evaluate(() => window.__emergence.engine.config.huntRest), 8);
  const before = await page.evaluate(() => window.__emergence.snapshot()); await page.waitForTimeout(150);
  assert.equal((await page.evaluate(() => window.__emergence.snapshot())).birthClock, before.birthClock);
  await page.locator('#lifecycle summary').click(); await page.locator('#lifecycle').scrollIntoViewIfNeeded();
  const out = path.resolve(__dirname, '../../checks/emergence');
  await page.screenshot({ path: path.join(out, 'lifecycle-desktop.png') });
  await page.locator('#control-predatorBirthInterval').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(out, 'predator-rules-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#control-predatorCap').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(out, 'predator-rules-mobile.png') });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.getByRole('button', { name: '鱼群场景', exact: true }).click();
  assert.equal(await page.locator('#control-birthInterval').inputValue(), '20');
  await page.getByRole('button', { name: '水滴场景', exact: true }).click();
  assert.equal(await page.locator('#lifecycle').isVisible(), false);
  await page.getByRole('button', { name: '宇宙场景', exact: true }).click();
  assert.equal(await page.locator('#lifecycle').isVisible(), false);
  assert.deepEqual(errors, []);
  fs.writeFileSync(path.join(out, 'lifecycle-results.json'), JSON.stringify({ behavior, persistence: true, pause: true, sceneIsolation: true, responsive: true, errors }, null, 2));
  console.log(`PASS: ${behavior.length} lifecycle assertions plus persistence, pause, per-scene isolation and desktop/mobile controls.`);
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => browser?.close());
