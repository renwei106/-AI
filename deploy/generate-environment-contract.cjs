'use strict';
const fs = require('node:fs'), path = require('node:path'), {createHash}=require('node:crypto');
const root=path.resolve(__dirname,'..'), source=path.join(__dirname,'environment-contract.json');
function validate(contract) {
  if(contract.schema!==1 || !contract.id || Object.keys(contract.profiles).sort().join(',')!=='development,production,test') throw Error('Invalid environment contract');
  const nativeWrite={method:'POST',path:'/api/shiyu/auth/tools',originScheme:'chrome-extension',idPattern:'^[a-p]{32}$',secFetchSite:'none',contentType:'application/json'};
  if(!contract.rules.nativeExtensionToolWrite || Object.keys(contract.rules.nativeExtensionToolWrite).sort().join(',')!==Object.keys(nativeWrite).sort().join(',')
    || Object.entries(nativeWrite).some(([key,value])=>contract.rules.nativeExtensionToolWrite[key]!==value)) throw Error('Native extension compatibility must remain limited to the existing JSON tool-write route');
  for(const [mode,profile] of Object.entries(contract.profiles)) {
    if(!Array.isArray(profile.extensionOrigins) || new Set(profile.extensionOrigins).size!==profile.extensionOrigins.length
      || profile.extensionOrigins.some(origin=>typeof origin!=='string'||!/^chrome-extension:\/\/[a-p]{32}$/.test(origin))
      || mode!=='production'&&profile.extensionOrigins.length) throw Error('Invalid or cross-environment extension origins');
    for(const scope of ['admin','site','tool']) {
      if(!Array.isArray(profile.browserOrigins[scope])) throw Error('Origin scope is missing');
      for(const value of profile.browserOrigins[scope]) {
        const url=new URL(value), local=['127.0.0.1','localhost','[::1]'].includes(url.hostname);
        if(url.origin!==value || url.username || url.password || (mode==='production' ? url.protocol!=='https:'||local : !local||url.protocol!=='http:')) throw Error('Cross-environment browser origin');
      }
    }
    for(const service of Object.values(profile.internalServices)) {
      const url=new URL(service.origin);
      if(url.origin!==service.origin || url.protocol!=='http:' || !contract.rules.internalServiceHostnames.includes(url.hostname) || typeof service.enabled!=='boolean') throw Error('Invalid internal service');
    }
    if(profile.allowDevelopmentFallback!==false) throw Error('Environment fallback is forbidden');
  }
  if(contract.profiles.test.browserOrigins.admin.length || contract.profiles.test.browserOrigins.site.length || contract.profiles.test.browserOrigins.tool.length) throw Error('Fixture origins must be explicit');
  return contract;
}
function outputs(adminRoot) {
  const bytes=fs.readFileSync(source), contract=validate(JSON.parse(bytes)), sha=createHash('sha256').update(bytes).digest('hex');
  const literal=JSON.stringify(contract,null,2);
  const rows=[{file:path.join(root,'dist/environment-policy-data.js'),contents:`/* Generated by deploy/generate-environment-contract.cjs; edit deploy/environment-contract.json. */\n;(function(root){\n  var value={environmentContract:${literal},environmentContractSha256:${JSON.stringify(sha)}};\n  if(typeof module==='object'&&module.exports) module.exports=value;\n  else root.ShiyuEnvironmentContract=value;\n})(typeof window==='object'?window:globalThis);\n`}];
  if(adminRoot) {
    const directory=path.resolve(adminRoot);
    if(!fs.existsSync(path.join(directory,'admin-plugins.ts'))) throw Error('Explicit admin source root is required');
    rows.push({file:path.join(directory,'environment-policy-data.ts'),contents:`// Generated from the canonical navigation deploy/environment-contract.json.\nexport const environmentContract = ${literal} as const\nexport const environmentContractSha256 = ${JSON.stringify(sha)}\n`});
    rows.push({file:path.join(directory,'environment-contract.json'),contents:bytes.toString('utf8')});
  }
  return rows;
}
if(require.main===module) {
  const args=process.argv.slice(2), index=args.indexOf('--admin-dir'), admin=index>=0?args[index+1]:undefined, check=args.includes('--check');
  if(index>=0&&!admin) throw Error('--admin-dir value is required');
  const rows=outputs(admin);
  for(const row of rows) {
    if(check) {if(!fs.existsSync(row.file)||fs.readFileSync(row.file,'utf8')!==row.contents) throw Error('Generated environment contract is stale: '+path.basename(row.file));}
    else fs.writeFileSync(row.file,row.contents);
  }
  console.log(JSON.stringify({status:'PASS',check,files:rows.map(row=>path.relative(root,row.file).replaceAll('\\','/'))}));
}
module.exports={validate,outputs};
